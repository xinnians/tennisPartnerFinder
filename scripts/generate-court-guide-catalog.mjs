import { readFileSync, writeFileSync } from "node:fs";

const catalogue = JSON.parse(readFileSync(new URL("../data/courts.json", import.meta.url), "utf8")).courts;
const content = JSON.parse(readFileSync(new URL("../data/court-guides.json", import.meta.url), "utf8")).guides;
const seen = new Set();
const entries = content.map(({ slug }) => {
  const matches = catalogue.filter((court) => court.slug === slug && court.city === "台北市");
  if (seen.has(slug) || matches.length !== 1 || !/^[a-z0-9-]+$/.test(slug))
    throw new Error(`Invalid published guide reference: ${slug}`);
  seen.add(slug);
  const key = /^[a-z][a-z0-9]*$/.test(slug) ? slug : JSON.stringify(slug);
  return `  ${key}: ${JSON.stringify(matches[0].name)},`;
});
const path = new URL("../src/features/guides/courtGuideCatalog.ts", import.meta.url);
const output = `// Generated by scripts/generate-court-guide-catalog.mjs; edit data/court-guides.json.\n// Only published Taipei guides enter browser intents; nationwide drafts never enter this map.\nexport const COURT_GUIDE_NAMES = {\n${entries.join("\n")}\n} as const;\n`;
if (process.argv.includes("--write")) writeFileSync(path, output);
else if (readFileSync(path, "utf8") !== output) throw new Error("Published guide catalogue is stale; regenerate it");
console.log(`Published guide catalogue matches ${entries.length} guides.`);
