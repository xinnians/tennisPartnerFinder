import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT_ROOT = fileURLToPath(new URL("../", import.meta.url));
const SCRIPT_PATH = fileURLToPath(import.meta.url);
const MAIN_SOURCE_PATH = "src/main.js";

export const DESIGN_SYSTEM_BUNDLE_PATH = "ds-bundle/_ds_bundle.css";
export const DESIGN_SYSTEM_TOKENS_PATH = "ds-bundle/tokens/tokens.css";

const normalizeSource = (source) =>
  source
    .replaceAll("\r\n", "\n")
    .replace(/[ \t]+$/gmu, "")
    .trimEnd();

export function productionCssSourcePaths(mainSource) {
  const paths = [...mainSource.matchAll(/^import\s+"(\.\/[^"\n]+\.css)";/gmu)].map(
    ([, importPath]) => `src/${importPath.slice(2)}`
  );
  assert.ok(paths.length > 0, `${MAIN_SOURCE_PATH} must import production CSS`);
  assert.equal(new Set(paths).size, paths.length, `${MAIN_SOURCE_PATH} must not import the same CSS twice`);
  return paths;
}

function tokenRootBlock(cssSources) {
  const candidates = cssSources.flatMap(({ path, source }) =>
    [...source.matchAll(/:root\s*\{[\s\S]*?\n\}/gu)]
      .map(([block]) => block)
      .filter((block) => block.includes("--color-ink:"))
      .map((block) => ({ block, path }))
  );
  assert.equal(candidates.length, 1, "production CSS must have exactly one design-token :root block");
  return candidates[0];
}

export function createDesignSystemArtifacts(cssSources) {
  assert.ok(cssSources.length > 0, "at least one production CSS source is required");
  const sourcePaths = cssSources.map(({ path }) => path);
  assert.equal(new Set(sourcePaths).size, sourcePaths.length, "production CSS source paths must be unique");

  const bundleHeader = [
    "/* Generated by `npm run sync:design-system`.",
    "   Do not edit this file directly. Sources follow the production cascade order from src/main.js. */",
  ].join("\n");
  const bundleSections = cssSources.map(({ path, source }) => `/* source: ${path} */\n${normalizeSource(source)}`);
  const bundle = `${bundleHeader}\n\n${bundleSections.join("\n\n")}\n`;

  const { block, path } = tokenRootBlock(cssSources);
  const tokenNames = [...block.matchAll(/(--[\w-]+)\s*:/gu)].map(([, name]) => name);
  assert.ok(tokenNames.length > 0, "design-token :root block must contain custom properties");
  assert.equal(new Set(tokenNames).size, tokenNames.length, "design-token names must be unique");
  const tokens = [
    "/* Generated by `npm run sync:design-system`.",
    `   Read-only token reference copied from ${path}; the full block also exists in _ds_bundle.css. */`,
    normalizeSource(block),
    "",
  ].join("\n");

  return { bundle, sourcePaths, tokenCount: tokenNames.length, tokens };
}

export function loadDesignSystemSnapshot({ root = PROJECT_ROOT } = {}) {
  const mainSource = readFileSync(resolve(root, MAIN_SOURCE_PATH), "utf8");
  const sourcePaths = productionCssSourcePaths(mainSource);
  const cssSources = sourcePaths.map((path) => ({ path, source: readFileSync(resolve(root, path), "utf8") }));
  const expected = createDesignSystemArtifacts(cssSources);
  return {
    actualBundle: readFileSync(resolve(root, DESIGN_SYSTEM_BUNDLE_PATH), "utf8"),
    actualTokens: readFileSync(resolve(root, DESIGN_SYSTEM_TOKENS_PATH), "utf8"),
    cssSources,
    expected,
    root,
  };
}

function firstDifferentLine(actual, expected) {
  const actualLines = normalizeSource(actual).split("\n");
  const expectedLines = normalizeSource(expected).split("\n");
  const length = Math.max(actualLines.length, expectedLines.length);
  for (let index = 0; index < length; index += 1) {
    if (actualLines[index] !== expectedLines[index]) return index + 1;
  }
  return null;
}

export function assertDesignSystemArtifactsCurrent({ actualBundle, actualTokens, expected }) {
  const differences = [
    [DESIGN_SYSTEM_BUNDLE_PATH, actualBundle, expected.bundle],
    [DESIGN_SYSTEM_TOKENS_PATH, actualTokens, expected.tokens],
  ].flatMap(([path, actual, wanted]) => {
    const line = firstDifferentLine(actual, wanted);
    return line === null ? [] : [`${path}:${line}`];
  });
  assert.deepEqual(
    differences,
    [],
    `design-system artifacts drifted at ${differences.join(", ")}; run npm run sync:design-system`
  );
}

export function writeDesignSystemArtifacts({ root = PROJECT_ROOT } = {}) {
  const mainSource = readFileSync(resolve(root, MAIN_SOURCE_PATH), "utf8");
  const sourcePaths = productionCssSourcePaths(mainSource);
  const cssSources = sourcePaths.map((path) => ({ path, source: readFileSync(resolve(root, path), "utf8") }));
  const artifacts = createDesignSystemArtifacts(cssSources);
  writeFileSync(resolve(root, DESIGN_SYSTEM_BUNDLE_PATH), artifacts.bundle);
  writeFileSync(resolve(root, DESIGN_SYSTEM_TOKENS_PATH), artifacts.tokens);
  return artifacts;
}

function main(arguments_) {
  assert.deepEqual(
    arguments_,
    arguments_.includes("--write") ? ["--write"] : ["--check"],
    "usage: node scripts/designSystemBundle.mjs --check|--write"
  );
  if (arguments_[0] === "--write") {
    const artifacts = writeDesignSystemArtifacts();
    console.log(
      `wrote design-system artifacts from ${artifacts.sourcePaths.length} CSS sources (${artifacts.tokenCount} tokens)`
    );
    return;
  }
  const snapshot = loadDesignSystemSnapshot();
  assertDesignSystemArtifactsCurrent(snapshot);
  console.log(
    `design-system artifacts are current (${snapshot.expected.sourcePaths.length} CSS sources, ${snapshot.expected.tokenCount} tokens)`
  );
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_PATH) {
  main(process.argv.slice(2));
}
